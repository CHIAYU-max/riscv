#!/usr/bin/env python3
"""Generate conv_data.h for sw/c/bench/conv.c: random INT8 activations and weights for one
3x3 convolution tile, and the checksum both conv_ref and conv_dot4 must reproduce.

usage: sw/c/gen_conv.py --out build/c/conv_data.h [--cin 32 --oh 2 --ow 2 --cout 4] [--unsigned-act]
"""
import argparse
import random

MASK = 0xFFFF_FFFF


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--out", required=True)
    parser.add_argument("--cin", type=int, default=32, help="input channels (multiple of 4)")
    parser.add_argument("--oh", type=int, default=2)
    parser.add_argument("--ow", type=int, default=2)
    parser.add_argument("--cout", type=int, default=4)
    parser.add_argument("--unsigned-act", action="store_true",
                        help="activations in 0..255 (dot4 rs1 unsigned) instead of -128..127")
    parser.add_argument("--seed", type=int, default=1)
    args = parser.parse_args()
    assert args.cin % 4 == 0

    rng = random.Random(args.seed)
    lo, hi = (0, 255) if args.unsigned_act else (-128, 127)
    act = [rng.randint(lo, hi) for _ in range((args.oh + 2) * (args.ow + 2) * args.cin)]
    wgt = [rng.randint(-128, 127) for _ in range(args.cout * 9 * args.cin)]

    total = 0
    for oc in range(args.cout):
        for oy in range(args.oh):
            for ox in range(args.ow):
                acc = 0
                for ky in range(3):
                    for kx in range(3):
                        a = ((oy + ky) * (args.ow + 2) + (ox + kx)) * args.cin
                        w = ((oc * 3 + ky) * 3 + kx) * args.cin
                        acc += sum(act[a + c] * wgt[w + c] for c in range(args.cin))
                total = (total * 31 + acc) & MASK

    act_t = "unsigned char" if args.unsigned_act else "signed char"
    macs = args.cout * args.oh * args.ow * 9 * args.cin
    with open(args.out, "w") as f:
        f.write(f"// generated by sw/c/gen_conv.py: {macs} MACs, seed {args.seed}\n")
        f.write(f"#define CIN {args.cin}\n#define OH {args.oh}\n#define OW {args.ow}\n#define COUT {args.cout}\n")
        f.write(f"#define DOT4_RS1_SIGNED {0 if args.unsigned_act else 1}\n")
        f.write(f"typedef {act_t} ACT_T;\n")
        f.write(f"#define EXPECTED 0x{total:08x}u\n")
        f.write("static const ACT_T act[] __attribute__((aligned(4))) = {" + ", ".join(map(str, act)) + "};\n")
        f.write("static const signed char wgt[] __attribute__((aligned(4))) = {" + ", ".join(map(str, wgt)) + "};\n")


if __name__ == "__main__":
    main()
