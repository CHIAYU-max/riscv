#!/usr/bin/env python3
"""Generate block_data.h for sw/c/bench/block.c: one U-Net encoder block on a small tile,
3x3 convolution (+ bias) -> requantize with ReLU -> 2x2 max pooling, all INT8 (or INT4 with --bits 4).

Activations are u8 and weights s8 (as dot4 expects); each output channel gets its own bias and
requant scale (M / 2^shift, zero point 0, so the clamp at 0 is the ReLU). The expected pooled
output is computed with the golden model's own requant (sw/iss.py), so the C reference in
sw/c/nnops.h is checked against it.

With --bits 4 the activations are u4 (0..15) and the weights s4 (symmetric, -7..7), packed two per byte (low nibble =
even channel) for sw/c/bench/block4.c; the requant output is clamped to 15 and the pooled output is packed too.

usage: sw/c/gen_block.py --out build/c/block_data.h [--cin 32 --oh 4 --ow 4 --cout 8] [--bits 8|4]
"""
import argparse
import random
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from iss import requant  # noqa: E402


def requant_params(scale):
    """M (u16) and shift with M / 2^shift ~= scale, M as large as possible."""
    shift = 31
    while shift > 0 and round(scale * (1 << shift)) > 0xFFFF:
        shift -= 1
    return round(scale * (1 << shift)), shift


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--out", required=True)
    parser.add_argument("--cin", type=int, default=32, help="input channels (multiple of 4)")
    parser.add_argument("--oh", type=int, default=4, help="convolution output height (even)")
    parser.add_argument("--ow", type=int, default=4, help="convolution output width (even)")
    parser.add_argument("--cout", type=int, default=8, help="output channels (multiple of 4)")
    parser.add_argument("--seed", type=int, default=1)
    parser.add_argument("--bits", type=int, choices=(8, 4), default=8, help="activation and weight width")
    args = parser.parse_args()
    cin, oh, ow, cout = args.cin, args.oh, args.ow, args.cout
    if args.bits == 4:
        assert cin % 8 == 0 and cout % 8 == 0, "INT4: cin and cout must be multiples of 8"
    assert cin % 4 == 0 and cout % 4 == 0 and oh % 2 == 0 and ow % 2 == 0

    rng = random.Random(args.seed)
    if args.bits == 8:
        amax, wmin, wmax, bmax, qmax = 255, -128, 127, 20000, 255
    else:   # same bias-to-accumulator ratio as INT8: 20000 * (15 * 8) / (255 * 128), about 74
        amax, wmin, wmax, bmax, qmax = 15, -7, 7, 74, 15
    act = [rng.randint(0, amax) for _ in range((oh + 2) * (ow + 2) * cin)]
    wgt = [rng.randint(wmin, wmax) for _ in range(cout * 9 * cin)]
    bias = [rng.randint(-bmax, bmax) for _ in range(cout)]

    # convolution, HWC: acc[(oy * ow + ox) * cout + oc]
    acc = [0] * (oh * ow * cout)
    for oy in range(oh):
        for ox in range(ow):
            for oc in range(cout):
                s = bias[oc]
                for ky in range(3):
                    for kx in range(3):
                        a = ((oy + ky) * (ow + 2) + (ox + kx)) * cin
                        w = ((oc * 3 + ky) * 3 + kx) * cin
                        s += sum(act[a + c] * wgt[w + c] for c in range(cin))
                acc[(oy * ow + ox) * cout + oc] = s

    # per-channel scale: the largest accumulator maps to ~1.25 x qmax (320 for INT8, 19 for INT4), so a few
    # outputs saturate
    top = 320 if args.bits == 8 else 19
    params = []
    for oc in range(cout):
        peak = max(acc[i] for i in range(oc, len(acc), cout))
        m, shift = requant_params(top / max(peak, 1))
        params.append(shift << 16 | m)
    out = [min(requant(acc[i] & 0xFFFF_FFFF, params[i % cout]), qmax) for i in range(len(acc))]

    # 2x2 max pooling, HWC
    ph, pw = oh // 2, ow // 2
    pooled = []
    for py in range(ph):
        for px in range(pw):
            for c in range(cout):
                pooled.append(max(out[((2 * py + dy) * ow + 2 * px + dx) * cout + c] for dy in (0, 1) for dx in (0, 1)))

    zeros = sum(v == 0 for v in out)
    sat = sum(v == qmax for v in out)
    macs = cout * oh * ow * 9 * cin

    def array(ctype, name, values):
        return f"static const {ctype} {name}[] __attribute__((aligned(4))) = {{" + ", ".join(map(str, values)) + "};\n"

    def pack4(values):
        return [(values[i] & 0xF) | (values[i + 1] & 0xF) << 4 for i in range(0, len(values), 2)]

    with open(args.out, "w") as f:
        f.write(f"// generated by sw/c/gen_block.py: INT{args.bits}, {macs} MACs, seed {args.seed}; "
                f"after requant {zeros} / {len(out)} zero (ReLU), {sat} saturated\n")
        f.write(f"#define BITS {args.bits}\n#define CIN {cin}\n#define OH {oh}\n#define OW {ow}\n#define COUT {cout}\n")
        if args.bits == 8:
            f.write(array("unsigned char", "act", act))
            f.write(array("signed char", "wgt", wgt))
        else:
            f.write(array("unsigned char", "act", pack4(act)))
            f.write(array("unsigned char", "wgt", pack4(wgt)))
        f.write(array("int", "bias", bias))
        f.write(array("unsigned", "rq_params", [f"0x{p:08x}u" for p in params]))
        f.write(array("unsigned char", "expected", pooled if args.bits == 8 else pack4(pooled)))


if __name__ == "__main__":
    main()
