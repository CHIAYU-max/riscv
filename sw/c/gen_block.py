#!/usr/bin/env python3
"""Generate block_data.h for sw/c/bench/block.c: one U-Net encoder block on a small tile,
3x3 convolution (+ bias) -> requantize with ReLU -> 2x2 max pooling, all INT8.

Activations are u8 and weights s8 (as dot4 expects); each output channel gets its own bias and
requant scale (M / 2^shift, zero point 0, so the clamp at 0 is the ReLU). The expected pooled
output is computed with the golden model's own requant (sw/iss.py), so the C reference in
sw/c/nnops.h is checked against it.

usage: sw/c/gen_block.py --out build/c/block_data.h [--cin 32 --oh 4 --ow 4 --cout 8] [--weights layer.json]

--weights takes the weights and bias of a trained layer (sw/export_layer.py) instead of random ones; the input
tile stays random, so no image is needed. CIN and COUT then come from the file.
"""
import argparse
import json
import random
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from iss import requant  # noqa: E402


def requant_params(scale):
    """M (u16) and shift with M / 2^shift ~= scale, M as large as possible."""
    shift = 31
    while shift > 0 and round(scale * (1 << shift)) > 0xFFFF:
        shift -= 1
    return round(scale * (1 << shift)), shift


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--out", required=True)
    parser.add_argument("--cin", type=int, default=32, help="input channels (multiple of 4)")
    parser.add_argument("--oh", type=int, default=4, help="convolution output height (even)")
    parser.add_argument("--ow", type=int, default=4, help="convolution output width (even)")
    parser.add_argument("--cout", type=int, default=8, help="output channels (multiple of 4)")
    parser.add_argument("--seed", type=int, default=1)
    parser.add_argument("--sparse24", action="store_true",
                        help="force 2:4 on random weights (two zeros per group of 4 input channels); trained 2:4 weights are detected")
    parser.add_argument("--weights", help="JSON from sw/export_layer.py: trained s8 weights and int32 bias")
    args = parser.parse_args()
    layer = json.load(open(args.weights)) if args.weights else None
    if layer:
        args.cin, args.cout = layer["cin"], layer["cout"]
    cin, oh, ow, cout = args.cin, args.oh, args.ow, args.cout
    assert cin % 4 == 0 and cout % 4 == 0 and oh % 2 == 0 and ow % 2 == 0

    rng = random.Random(args.seed)
    act = [rng.randint(0, 255) for _ in range((oh + 2) * (ow + 2) * cin)]
    wgt = [rng.randint(-128, 127) for _ in range(cout * 9 * cin)]
    bias = [rng.randint(-20000, 20000) for _ in range(cout)]
    if layer:
        wgt, bias = layer["wgt"], layer["bias"]
        assert len(wgt) == cout * 9 * cin and len(bias) == cout
    if args.sparse24 and not layer:
        for g in range(0, len(wgt), 4):
            for k in rng.sample(range(4), 2):
                wgt[g + k] = 0
    groups = [wgt[g:g + 4] for g in range(0, len(wgt), 4)]
    sparse24 = all(sum(v != 0 for v in grp) <= 2 for grp in groups)

    # convolution, HWC: acc[(oy * ow + ox) * cout + oc]
    acc = [0] * (oh * ow * cout)
    for oy in range(oh):
        for ox in range(ow):
            for oc in range(cout):
                s = bias[oc]
                for ky in range(3):
                    for kx in range(3):
                        a = ((oy + ky) * (ow + 2) + (ox + kx)) * cin
                        w = ((oc * 3 + ky) * 3 + kx) * cin
                        s += sum(act[a + c] * wgt[w + c] for c in range(cin))
                acc[(oy * ow + ox) * cout + oc] = s

    # per-channel scale: the largest accumulator maps to ~320, so a few outputs saturate at 255
    params = []
    for oc in range(cout):
        peak = max(acc[i] for i in range(oc, len(acc), cout))
        m, shift = requant_params(320 / max(peak, 1))
        params.append(shift << 16 | m)
    out = [requant(acc[i] & 0xFFFF_FFFF, params[i % cout]) for i in range(len(acc))]

    # 2x2 max pooling, HWC
    ph, pw = oh // 2, ow // 2
    pooled = []
    for py in range(ph):
        for px in range(pw):
            for c in range(cout):
                pooled.append(max(out[((2 * py + dy) * ow + 2 * px + dx) * cout + c] for dy in (0, 1) for dx in (0, 1)))

    zeros = sum(v == 0 for v in out)
    sat = sum(v == 255 for v in out)
    macs = cout * oh * ow * 9 * cin

    def array(ctype, name, values):
        return f"static const {ctype} {name}[] __attribute__((aligned(4))) = {{" + ", ".join(map(str, values)) + "};\n"

    with open(args.out, "w") as f:
        src = f"weights of {layer['layer']} (first {cout} of {layer['cout_total']} output channels)" if layer else "random weights"
        f.write(f"// generated by sw/c/gen_block.py: {macs} MACs, {src}, input seed {args.seed}; "
                f"after requant {zeros} / {len(out)} zero (ReLU), {sat} saturated\n")
        f.write(f"#define CIN {cin}\n#define OH {oh}\n#define OW {ow}\n#define COUT {cout}\n")
        f.write(array("unsigned char", "act", act))
        f.write(array("signed char", "wgt", wgt))
        f.write(array("int", "bias", bias))
        f.write(array("unsigned", "rq_params", [f"0x{p:08x}u" for p in params]))
        f.write(array("unsigned char", "expected", pooled))
        if sparse24:
            # each group: its (up to) two non-zeros in channel order with their channel indices; a group with
            # fewer than two non-zeros is padded with weight 0 at an unused index
            packed = []
            for grp in groups:
                nz = [k for k in range(4) if grp[k] != 0]
                nz += [k for k in range(4) if k not in nz][:2 - len(nz)]
                packed.append([(grp[k], k) for k in sorted(nz)])
            wa = [(pk[0][0] & 0xFF) | (pk[1][0] & 0xFF) << 8 | pk[0][1] << 16 | pk[1][1] << 18 for pk in packed]
            f.write("#define SPARSE24 1\n")
            f.write(array("unsigned", "wsa", [f"0x{v:08x}u" for v in wa]))
            if cin % 32 == 0:
                wb, ib = [], []
                for p0, p1 in zip(packed[0::2], packed[1::2]):
                    ws = [p0[0][0], p0[1][0], p1[0][0], p1[1][0]]
                    wb.append(sum((v & 0xFF) << (8 * k) for k, v in enumerate(ws)))
                    ib.append(p0[0][1] | p0[1][1] << 2 | p1[0][1] << 4 | p1[1][1] << 6)
                f.write("#define SPARSE24_PAIRS 1\n")
                f.write(array("unsigned", "wsb", [f"0x{v:08x}u" for v in wb]))
                f.write(array("unsigned char", "isb", ib))
            dense_b, a_b = cout * 9 * cin, 4 * len(wa)
            b_b = cout * 9 * cin // 2 + cout * 9 * cin // 8
            f.write(f"// weight bytes: dense {dense_b}, sdot4 packing {a_b}, sdot8 packing {b_b}\n")


if __name__ == "__main__":
    main()
