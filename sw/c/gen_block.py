#!/usr/bin/env python3
"""Generate block_data.h for sw/c/bench/block.c: one U-Net encoder block on a small tile,
3x3 convolution (+ bias) -> requantize with ReLU -> 2x2 max pooling, all INT8.

Activations are u8 and weights s8 (as dot4 expects); each output channel gets its own bias and
requant scale (M / 2^shift, zero point 0, so the clamp at 0 is the ReLU). The expected pooled
output is computed with the golden model's own requant (sw/iss.py), so the C reference in
sw/c/nnops.h is checked against it.

usage: sw/c/gen_block.py --out build/c/block_data.h [--cin 32 --oh 4 --ow 4 --cout 8]
"""
import argparse
import random
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from iss import requant  # noqa: E402


def requant_params(scale):
    """M (u16) and shift with M / 2^shift ~= scale, M as large as possible."""
    shift = 31
    while shift > 0 and round(scale * (1 << shift)) > 0xFFFF:
        shift -= 1
    return round(scale * (1 << shift)), shift


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--out", required=True)
    parser.add_argument("--cin", type=int, default=32, help="input channels (multiple of 4)")
    parser.add_argument("--oh", type=int, default=4, help="convolution output height (even)")
    parser.add_argument("--ow", type=int, default=4, help="convolution output width (even)")
    parser.add_argument("--cout", type=int, default=8, help="output channels (multiple of 4)")
    parser.add_argument("--seed", type=int, default=1)
    args = parser.parse_args()
    cin, oh, ow, cout = args.cin, args.oh, args.ow, args.cout
    assert cin % 4 == 0 and cout % 4 == 0 and oh % 2 == 0 and ow % 2 == 0

    rng = random.Random(args.seed)
    act = [rng.randint(0, 255) for _ in range((oh + 2) * (ow + 2) * cin)]
    wgt = [rng.randint(-128, 127) for _ in range(cout * 9 * cin)]
    bias = [rng.randint(-20000, 20000) for _ in range(cout)]

    # convolution, HWC: acc[(oy * ow + ox) * cout + oc]
    acc = [0] * (oh * ow * cout)
    for oy in range(oh):
        for ox in range(ow):
            for oc in range(cout):
                s = bias[oc]
                for ky in range(3):
                    for kx in range(3):
                        a = ((oy + ky) * (ow + 2) + (ox + kx)) * cin
                        w = ((oc * 3 + ky) * 3 + kx) * cin
                        s += sum(act[a + c] * wgt[w + c] for c in range(cin))
                acc[(oy * ow + ox) * cout + oc] = s

    # per-channel scale: the largest accumulator maps to ~320, so a few outputs saturate at 255
    params = []
    for oc in range(cout):
        peak = max(acc[i] for i in range(oc, len(acc), cout))
        m, shift = requant_params(320 / max(peak, 1))
        params.append(shift << 16 | m)
    out = [requant(acc[i] & 0xFFFF_FFFF, params[i % cout]) for i in range(len(acc))]

    # 2x2 max pooling, HWC
    ph, pw = oh // 2, ow // 2
    pooled = []
    for py in range(ph):
        for px in range(pw):
            for c in range(cout):
                pooled.append(max(out[((2 * py + dy) * ow + 2 * px + dx) * cout + c] for dy in (0, 1) for dx in (0, 1)))

    zeros = sum(v == 0 for v in out)
    sat = sum(v == 255 for v in out)
    macs = cout * oh * ow * 9 * cin

    def array(ctype, name, values):
        return f"static const {ctype} {name}[] __attribute__((aligned(4))) = {{" + ", ".join(map(str, values)) + "};\n"

    with open(args.out, "w") as f:
        f.write(f"// generated by sw/c/gen_block.py: {macs} MACs, seed {args.seed}; "
                f"after requant {zeros} / {len(out)} zero (ReLU), {sat} saturated\n")
        f.write(f"#define CIN {cin}\n#define OH {oh}\n#define OW {ow}\n#define COUT {cout}\n")
        f.write(array("unsigned char", "act", act))
        f.write(array("signed char", "wgt", wgt))
        f.write(array("int", "bias", bias))
        f.write(array("unsigned", "rq_params", [f"0x{p:08x}u" for p in params]))
        f.write(array("unsigned char", "expected", pooled))


if __name__ == "__main__":
    main()
