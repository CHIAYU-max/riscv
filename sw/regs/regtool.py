#!/usr/bin/env python3
"""Generate the register block, C header and markdown map from one register table (sw/regs/regs.json).

After Chipyard's declarative register maps and OpenTitan's reggen (docs/design-notes.md, "Ideas taken from
Chipyard" item 1 and "Ideas taken from OpenTitan" item 4): the table is the single source, so the RTL decoder, the
host program's addresses and the README table cannot drift apart. The table format is JSON, a subset of the hjson
reggen uses. DRAFT (2026-11-22): the registers and addresses are placeholders until the 2/20 session.

Registers marked "external" are decoded elsewhere (fpga/rtl/soc.v) and only appear in the header and the map.
The others form one SystemVerilog module with a simple single-cycle request interface (valid, write enable, word
offset, write data; read data the next cycle) and lowRISC-style names (_i / _o, _q). Field access types:
  rw        stored here, read back; output <reg>_<field>_q_o
  ro        read from the hardware input <reg>_<field>_i
  wo_pulse  writing 1 gives a one-cycle pulse on <reg>_<field>_o; reads as 0

usage: sw/regs/regtool.py sw/regs/regs.json --out build/regs   (writes <name>.sv, <name>.h, <name>.md)
"""
import argparse
import json
from pathlib import Path

ACCESS = {"rw", "ro", "wo", "wo_pulse"}


def load(path):
    t = json.loads(Path(path).read_text())
    base = int(t["base"], 16)
    regs, seen = [], {}
    for r in t["registers"]:
        r["off"] = int(r["offset"], 16)
        assert r["off"] % 4 == 0, f"{r['name']}: offset not word aligned"
        assert r["off"] not in seen, f"{r['name']}: offset {r['offset']} already used by {seen.get(r['off'])}"
        seen[r["off"]] = r["name"]
        used = 0
        for f in r["fields"]:
            assert f["access"] in ACCESS, f"{r['name']}.{f['name']}: access {f['access']}"
            assert not r.get("external") or f["access"] in ("wo", "ro"), f"{r['name']}: external registers are wo / ro"
            assert r.get("external") or f["access"] != "wo", f"{r['name']}.{f['name']}: use wo_pulse inside the block"
            mask = ((1 << f["width"]) - 1) << f["lsb"]
            assert f["lsb"] + f["width"] <= t["width"] and not used & mask, f"{r['name']}.{f['name']}: overlapping bits"
            used |= mask
        regs.append(r)
    return t, base, sorted(regs, key=lambda r: r["off"])


def gen_sv(t, regs):
    inner = [r for r in regs if not r.get("external")]
    lo = min(r["off"] for r in inner)
    span = max(r["off"] for r in inner) - lo + 4
    aw = max(1, (span // 4 - 1).bit_length())
    ports, decl, wr, rd, outs = [], [], [], [], []
    for r in inner:
        idx = (r["off"] - lo) // 4
        rd_bits = []
        for f in r["fields"]:
            n, hi, lsb, w = f"{r['name'].lower()}_{f['name']}", f["lsb"] + f["width"] - 1, f["lsb"], f["width"]
            vec = f"[{w - 1}:0] " if w > 1 else ""
            if f["access"] == "rw":
                ports.append(f"  output logic {vec}{n}_q_o")
                decl.append(f"  logic {vec}{n}_q;")
                rst = int(f.get("reset", "0x0"), 16)
                wr.append((f"      {n}_q <= {w}'h{rst:x};", f"      if (req_valid_i && req_we_i && req_addr_i == {aw}'d{idx}) {n}_q <= req_wdata_i[{hi}:{lsb}];"))
                outs.append(f"  assign {n}_q_o = {n}_q;")
                rd_bits.append((lsb, w, f"{n}_q"))
            elif f["access"] == "ro":
                ports.append(f"  input  logic {vec}{n}_i")
                rd_bits.append((lsb, w, f"{n}_i"))
            else:
                ports.append(f"  output logic {vec}{n}_o")
                outs.append(f"  assign {n}_o = (req_valid_i && req_we_i && req_addr_i == {aw}'d{idx}) ? req_wdata_i[{hi}:{lsb}] : '0;")
        if rd_bits:
            word = []
            pos = t["width"]
            for lsb, w, sig in sorted(rd_bits, reverse=True):
                if pos > lsb + w:
                    word.append(f"{pos - lsb - w}'b0")
                word.append(sig)
                pos = lsb
            if pos:
                word.append(f"{pos}'b0")
            rd.append(f"      {aw}'d{idx}: rdata_d = {{{', '.join(word)}}};" if len(word) > 1 else f"      {aw}'d{idx}: rdata_d = {word[0]};")
    name = t["name"]
    lines = [f"// Generated by sw/regs/regtool.py from {t.get('_source', 'sw/regs/regs.json')}; do not edit.",
             f"// Register block at offsets 0x{lo:03x}..0x{lo + span - 4:03x} from 0x{int(t['base'], 16):08x}; "
             "req_addr_i is the word index inside the block.",
             f"module {name} (", "  input  logic        clk_i,", "  input  logic        rst_ni,",
             "  input  logic        req_valid_i,", "  input  logic        req_we_i,",
             f"  input  logic [{aw - 1}:0]  req_addr_i,", "  input  logic [31:0] req_wdata_i,",
             "  output logic [31:0] rdata_o,"]
    lines += [p + "," for p in ports[:-1]] + [ports[-1]] + [");", ""]
    lines += decl + ["  logic [31:0] rdata_d, rdata_q;", ""]
    if wr:
        lines += ["  always_ff @(posedge clk_i or negedge rst_ni) begin", "    if (!rst_ni) begin"]
        lines += [a for a, _ in wr] + ["    end else begin"] + [b for _, b in wr] + ["    end", "  end", ""]
    lines += ["  always_comb begin", "    rdata_d = '0;", "    unique case (req_addr_i)"] + rd + ["      default: rdata_d = '0;", "    endcase", "  end", "",
              "  always_ff @(posedge clk_i or negedge rst_ni) begin", "    if (!rst_ni) rdata_q <= '0;",
              "    else if (req_valid_i && !req_we_i) rdata_q <= rdata_d;", "  end", "",
              "  assign rdata_o = rdata_q;"] + outs + ["", "endmodule", ""]
    return "\n".join(lines)


def gen_h(t, base, regs):
    guard = t["name"].upper() + "_H"
    lines = [f"// Generated by sw/regs/regtool.py from sw/regs/regs.json; do not edit.", f"#ifndef {guard}", f"#define {guard}", ""]
    for r in regs:
        lines.append(f"#define REG_{r['name']:<12} (*(volatile unsigned int *)0x{base + r['off']:08x}u)  // {r['desc']}")
        for f in r["fields"]:
            if f["width"] < t["width"]:
                key = f"{r['name']}_{f['name'].upper()}"
                lines.append(f"#define {key}_LSB {f['lsb']}")
                lines.append(f"#define {key}_MASK 0x{((1 << f['width']) - 1) << f['lsb']:08x}u")
    return "\n".join(lines + ["", f"#endif  // {guard}", ""])


def gen_md(t, base, regs):
    lines = [f"<!-- Generated by sw/regs/regtool.py from sw/regs/regs.json; do not edit. -->",
             "| Address | Register | Bits | Field | Access | Description |", "| --- | --- | --- | --- | --- | --- |"]
    for r in regs:
        for i, f in enumerate(r["fields"]):
            bits = f"[{f['lsb'] + f['width'] - 1}:{f['lsb']}]" if f["width"] > 1 else f"[{f['lsb']}]"
            where = " (in `soc.v`)" if r.get("external") else ""
            addr = f"`0x{base + r['off']:08x}`" if i == 0 else ""
            reg = f"`{r['name']}`{where}" if i == 0 else ""
            lines.append(f"| {addr} | {reg} | {bits} | `{f['name']}` | {f['access']} | {f['desc'].replace('|', chr(92) + '|')} |")
    return "\n".join(lines) + "\n"


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("table")
    ap.add_argument("--out", required=True)
    args = ap.parse_args()
    t, base, regs = load(args.table)
    t["_source"] = args.table
    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    (out / f"{t['name']}.sv").write_text(gen_sv(t, regs))
    (out / f"{t['name']}.h").write_text(gen_h(t, base, regs))
    (out / f"{t['name']}.md").write_text(gen_md(t, base, regs))
    print(f"{len(regs)} registers ({sum(1 for r in regs if not r.get('external'))} in the block) -> {out}/{t['name']}.{{sv,h,md}}")


if __name__ == "__main__":
    main()
